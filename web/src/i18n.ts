const DICTS: Record<LocaleId, Dict> = { zh, en };

export type Text = Dict;

/** 当前语言的文案字典。组件里 `const t = useT()` 后按 `t.nav.tasks` 取值。 */
export function useT(): Dict {
  return DICTS[useLocale()];
}

/** 拿指定语言的字典（非响应场景，如工具函数）。 */
export function dictOf(locale: LocaleId): Dict {
  return DICTS[locale];
}
