inline std::wstring Normalize(std::wstring value) {
  size_t first=0, last=value.size();
  while(first<last && std::iswspace(value[first])) ++first;
  while(last>first && std::iswspace(value[last-1])) --last;
  value=value.substr(first,last-first);
  for(auto& c:value) c=static_cast<wchar_t>(std::towupper(c));
  return value;
}
inline std::optional<int> Code(const std::wstring& name,const std::wstring& type) {
  const auto& table=Tables(); auto platform=table.find(type);
  if(platform==table.end()) platform=table.find(L"Win32");
  if(platform==table.end()) return std::nullopt;
  auto key=platform->second.find(Normalize(name));
  if(key==platform->second.end()) return std::nullopt;
  return key->second;
}
inline bool Known(const std::wstring& name) {
  const auto normalized=Normalize(name);
  for(const auto& platform:Tables()) if(platform.second.count(normalized)) return true;
  return false;
}
